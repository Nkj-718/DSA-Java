class literals {
    public static void main(String[] args){
        int a=520; //The value of a variable is Literal.
        int bin=0b1011011; //Binary Value
        int hex=0x842E; //Hexadecimal Value
        System.out.println(a);
        System.out.println(bin);
        System.out.println(hex);
    }    
}
